-- Dimensional warehouse (spec section 9)
CREATE EXTENSION IF NOT EXISTS btree_gist;
CREATE SCHEMA IF NOT EXISTS dwh;

-- ============================================================ static dimensions
CREATE TABLE dwh.dim_date (
    date_key                        INT PRIMARY KEY,          -- YYYYMMDD; -1 unknown, -2 n/a
    full_date                       DATE UNIQUE,
    day_of_week_num                 SMALLINT CHECK (day_of_week_num BETWEEN 1 AND 7),  -- ISO
    day_name                        TEXT NOT NULL,
    is_weekend                      BOOLEAN NOT NULL DEFAULT FALSE,
    iso_week                        SMALLINT,
    iso_year                        SMALLINT,
    month_num                       SMALLINT CHECK (month_num BETWEEN 1 AND 12),
    month_name                      TEXT,
    quarter                         SMALLINT CHECK (quarter BETWEEN 1 AND 4),
    year                            SMALLINT,
    academic_year                   TEXT,
    is_holiday                      BOOLEAN NOT NULL DEFAULT FALSE,
    holiday_name                    TEXT,
    is_school_break                 BOOLEAN NOT NULL DEFAULT FALSE,
    is_school_day                   BOOLEAN NOT NULL DEFAULT FALSE,
    is_first_school_day_after_break BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_dim_date_regular_rows CHECK (
        date_key < 0 OR (
            full_date IS NOT NULL
            AND date_key = to_char(full_date, 'YYYYMMDD')::INT
            AND is_school_day = (NOT is_weekend AND NOT is_holiday AND NOT is_school_break)
        )
    )
);

CREATE TABLE dwh.dim_time_of_day (
    time_key   INT PRIMARY KEY,                               -- HHMM; -1 unknown, -2 n/a
    hour       SMALLINT CHECK (hour BETWEEN 0 AND 23),
    minute     SMALLINT CHECK (minute BETWEEN 0 AND 59),
    time_label TEXT NOT NULL,
    day_part   TEXT NOT NULL CHECK (day_part IN (
        'NIGHT', 'EARLY_MORNING', 'MORNING', 'MIDDAY', 'AFTERNOON', 'EVENING',
        'UNKNOWN', 'NOT_APPLICABLE')),
    CONSTRAINT ck_dim_time_regular_rows CHECK (
        time_key < 0 OR (hour IS NOT NULL AND minute IS NOT NULL AND time_key = hour * 100 + minute)
    )
);

CREATE TABLE dwh.dim_event_type (
    event_type_key   INT PRIMARY KEY,
    event_type_code  TEXT NOT NULL,
    direction        TEXT NOT NULL,
    event_type_label TEXT NOT NULL,
    UNIQUE (event_type_code, direction)
);

-- Junk dimension: direction, status and cancel reason combined (14 rows + unknown)
CREATE TABLE dwh.dim_trip_profile (
    trip_profile_key INT PRIMARY KEY,
    direction        TEXT NOT NULL,
    trip_status      TEXT NOT NULL,
    cancel_reason    TEXT NOT NULL,                           -- NONE when not cancelled
    profile_label    TEXT NOT NULL,
    UNIQUE (direction, trip_status, cancel_reason),
    CONSTRAINT ck_trip_profile_cancel CHECK (
        trip_profile_key < 0 OR ((trip_status = 'CANCELLED') = (cancel_reason <> 'NONE'))
    )
);

-- ============================================================ SCD1 dimensions
CREATE TABLE dwh.dim_route (
    route_key           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id            INT NOT NULL UNIQUE,
    route_name          TEXT NOT NULL,
    planned_distance_km NUMERIC(6,2),
    is_active           BOOLEAN,
    created_load_id     INT NOT NULL REFERENCES ctl.etl_run (run_id),
    updated_load_id     INT NOT NULL REFERENCES ctl.etl_run (run_id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE dwh.dim_driver (
    driver_key      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id       INT NOT NULL UNIQUE,
    driver_name     TEXT NOT NULL,
    hire_date       DATE,
    driver_status   TEXT NOT NULL,
    created_load_id INT NOT NULL REFERENCES ctl.etl_run (run_id),
    updated_load_id INT NOT NULL REFERENCES ctl.etl_run (run_id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================ SCD2 dimensions
-- Half-open validity: a version is valid for effective_date <= d < expiration_date.
-- Open versions end on 9999-12-31 and are flagged is_current.
CREATE TABLE dwh.dim_student (
    student_key       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id        INT NOT NULL,
    student_name      TEXT NOT NULL,                  -- SCD1
    grade_level       SMALLINT CHECK (grade_level BETWEEN 1 AND 12),   -- SCD1
    student_status    TEXT NOT NULL,                  -- SCD1
    home_neighborhood TEXT NOT NULL,                  -- SCD2
    home_city         TEXT NOT NULL,                  -- SCD2
    effective_date    DATE NOT NULL,
    expiration_date   DATE NOT NULL,
    is_current        BOOLEAN NOT NULL,
    scd2_hash         TEXT NOT NULL,
    created_load_id   INT NOT NULL REFERENCES ctl.etl_run (run_id),
    updated_load_id   INT NOT NULL REFERENCES ctl.etl_run (run_id),
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_student_current CHECK (is_current = (expiration_date = DATE '9999-12-31')),
    CONSTRAINT ck_student_dates   CHECK (effective_date < expiration_date),
    CONSTRAINT uq_student_version UNIQUE (student_id, effective_date),
    CONSTRAINT ex_student_no_overlap EXCLUDE USING gist (
        student_id WITH =, daterange(effective_date, expiration_date) WITH &&)
);
CREATE UNIQUE INDEX uq_student_current ON dwh.dim_student (student_id) WHERE is_current;

CREATE TABLE dwh.dim_stop (
    stop_key        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stop_id         INT NOT NULL,
    stop_name       TEXT NOT NULL,                    -- SCD1
    stop_sequence   SMALLINT,                         -- SCD1
    is_active       BOOLEAN,                          -- SCD1
    route_id        INT,                              -- SCD2 (a natural id, not a dim key)
    latitude        NUMERIC(9,6),                     -- SCD2
    longitude       NUMERIC(9,6),                     -- SCD2
    effective_date  DATE NOT NULL,
    expiration_date DATE NOT NULL,
    is_current      BOOLEAN NOT NULL,
    scd2_hash       TEXT NOT NULL,
    created_load_id INT NOT NULL REFERENCES ctl.etl_run (run_id),
    updated_load_id INT NOT NULL REFERENCES ctl.etl_run (run_id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_stop_current CHECK (is_current = (expiration_date = DATE '9999-12-31')),
    CONSTRAINT ck_stop_dates   CHECK (effective_date < expiration_date),
    CONSTRAINT uq_stop_version UNIQUE (stop_id, effective_date),
    CONSTRAINT ex_stop_no_overlap EXCLUDE USING gist (
        stop_id WITH =, daterange(effective_date, expiration_date) WITH &&)
);
CREATE UNIQUE INDEX uq_stop_current ON dwh.dim_stop (stop_id) WHERE is_current;

CREATE TABLE dwh.dim_bus (
    bus_key         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id          INT NOT NULL,
    plate_number    TEXT NOT NULL,                    -- SCD1
    model_year      SMALLINT,                         -- SCD1
    bus_status      TEXT NOT NULL,                    -- SCD1
    seat_capacity   SMALLINT CHECK (seat_capacity > 0),   -- SCD2
    effective_date  DATE NOT NULL,
    expiration_date DATE NOT NULL,
    is_current      BOOLEAN NOT NULL,
    scd2_hash       TEXT NOT NULL,
    created_load_id INT NOT NULL REFERENCES ctl.etl_run (run_id),
    updated_load_id INT NOT NULL REFERENCES ctl.etl_run (run_id),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_bus_current CHECK (is_current = (expiration_date = DATE '9999-12-31')),
    CONSTRAINT ck_bus_dates   CHECK (effective_date < expiration_date),
    CONSTRAINT uq_bus_version UNIQUE (bus_id, effective_date),
    CONSTRAINT ex_bus_no_overlap EXCLUDE USING gist (
        bus_id WITH =, daterange(effective_date, expiration_date) WITH &&)
);
CREATE UNIQUE INDEX uq_bus_current ON dwh.dim_bus (bus_id) WHERE is_current;

-- ============================================================ fact tables
-- Grain: the outcome of one student on one trip (picked up, dropped off or no-show).
CREATE TABLE dwh.fact_stop_event (
    stop_event_key     BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    trip_id            BIGINT NOT NULL,                 -- degenerate dimension
    service_date_key   INT NOT NULL REFERENCES dwh.dim_date (date_key),
    scheduled_time_key INT NOT NULL REFERENCES dwh.dim_time_of_day (time_key),
    actual_time_key    INT NOT NULL REFERENCES dwh.dim_time_of_day (time_key),  -- -2 for NO_SHOW
    student_key        INT NOT NULL REFERENCES dwh.dim_student (student_key),
    stop_key           INT NOT NULL REFERENCES dwh.dim_stop (stop_key),
    route_key          INT NOT NULL REFERENCES dwh.dim_route (route_key),
    bus_key            INT NOT NULL REFERENCES dwh.dim_bus (bus_key),
    driver_key         INT NOT NULL REFERENCES dwh.dim_driver (driver_key),
    event_type_key     INT NOT NULL REFERENCES dwh.dim_event_type (event_type_key),
    delay_minutes      NUMERIC(6,2),                    -- actual - scheduled; NULL for NO_SHOW
    ridership_count    SMALLINT NOT NULL CHECK (ridership_count IN (0, 1)),
    no_show_count      SMALLINT NOT NULL CHECK (no_show_count IN (0, 1)),
    late_count         SMALLINT NOT NULL CHECK (late_count IN (0, 1)),
    load_id            INT NOT NULL REFERENCES ctl.etl_run (run_id),
    loaded_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_fact_stop_event_grain UNIQUE (trip_id, student_key),
    CONSTRAINT ck_stop_event_outcome CHECK (ridership_count + no_show_count = 1),
    CONSTRAINT ck_no_show_has_no_delay CHECK (no_show_count = 0 OR delay_minutes IS NULL),
    CONSTRAINT ck_late_needs_delay CHECK (late_count = 0 OR delay_minutes IS NOT NULL)
);

-- Grain: one trip (route, direction, service date), updated as it progresses.
CREATE TABLE dwh.fact_trip_lifecycle (
    trip_lifecycle_key          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    trip_id                     BIGINT NOT NULL UNIQUE,  -- degenerate dimension
    service_date_key            INT NOT NULL REFERENCES dwh.dim_date (date_key),
    route_key                   INT NOT NULL REFERENCES dwh.dim_route (route_key),
    bus_key                     INT NOT NULL REFERENCES dwh.dim_bus (bus_key),
    driver_key                  INT NOT NULL REFERENCES dwh.dim_driver (driver_key),
    trip_profile_key            INT NOT NULL REFERENCES dwh.dim_trip_profile (trip_profile_key),
    scheduled_start_time_key    INT NOT NULL DEFAULT -2 REFERENCES dwh.dim_time_of_day (time_key),
    actual_start_time_key       INT NOT NULL DEFAULT -2 REFERENCES dwh.dim_time_of_day (time_key),
    first_stop_time_key         INT NOT NULL DEFAULT -2 REFERENCES dwh.dim_time_of_day (time_key),
    last_stop_time_key          INT NOT NULL DEFAULT -2 REFERENCES dwh.dim_time_of_day (time_key),
    scheduled_arrival_time_key  INT NOT NULL DEFAULT -2 REFERENCES dwh.dim_time_of_day (time_key),
    actual_arrival_time_key     INT NOT NULL DEFAULT -2 REFERENCES dwh.dim_time_of_day (time_key),
    start_delay_min             NUMERIC(7,2),
    start_to_first_stop_min     NUMERIC(7,2),
    first_to_last_stop_min      NUMERIC(7,2),
    last_stop_to_arrival_min    NUMERIC(7,2),
    total_duration_min          NUMERIC(7,2),
    arrival_delay_min           NUMERIC(7,2),
    students_expected           SMALLINT,
    students_served             SMALLINT,
    students_no_show            SMALLINT,
    km_driven                   NUMERIC(8,1),
    is_complete                 BOOLEAN NOT NULL,       -- COMPLETED or CANCELLED
    first_loaded_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    load_id                     INT NOT NULL REFERENCES ctl.etl_run (run_id)
);

-- Grain: one bus on one school day, including days with no trips.
CREATE TABLE dwh.fact_bus_daily (
    service_date_key   INT NOT NULL REFERENCES dwh.dim_date (date_key),
    bus_key            INT NOT NULL REFERENCES dwh.dim_bus (bus_key),
    trips_scheduled    SMALLINT NOT NULL CHECK (trips_scheduled >= 0),
    trips_completed    SMALLINT NOT NULL CHECK (trips_completed >= 0),
    trips_cancelled    SMALLINT NOT NULL CHECK (trips_cancelled >= 0),
    km_driven          NUMERIC(8,1) NOT NULL DEFAULT 0,
    students_transported INT NOT NULL DEFAULT 0,
    seat_capacity      SMALLINT NOT NULL,               -- semi-additive: never sum across days
    seat_trips_offered INT NOT NULL,                    -- seat_capacity * trips_completed
    load_id            INT NOT NULL REFERENCES ctl.etl_run (run_id),
    loaded_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (service_date_key, bus_key)
);

