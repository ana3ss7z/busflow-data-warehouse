-- Control and audit schema (spec 8.3)
CREATE SCHEMA IF NOT EXISTS ctl;

CREATE TABLE ctl.etl_run (
    run_id      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    status      TEXT NOT NULL CHECK (status IN ('RUNNING', 'SUCCESS', 'FAILED')),
    as_of_ts    TIMESTAMPTZ NOT NULL,   -- the simulated "now" of the run
    mode        TEXT NOT NULL,
    notes       TEXT,
    CHECK (finished_at IS NULL OR finished_at >= started_at)
);

-- Run 0 is the bootstrap run: it owns the special dimension members (-1, -2).
INSERT INTO ctl.etl_run (run_id, started_at, finished_at, status, as_of_ts, mode, notes)
VALUES (0, TIMESTAMPTZ '1900-01-01 00:00+00', TIMESTAMPTZ '1900-01-01 00:00+00', 'SUCCESS',
        TIMESTAMPTZ '1900-01-01 00:00+00', 'BOOTSTRAP', 'Owner of the special dimension members');

CREATE TABLE ctl.etl_step_log (
    run_id        INT NOT NULL REFERENCES ctl.etl_run (run_id),
    step_name     TEXT NOT NULL,
    rows_read     BIGINT NOT NULL DEFAULT 0,
    rows_inserted BIGINT NOT NULL DEFAULT 0,
    rows_updated  BIGINT NOT NULL DEFAULT 0,
    rows_rejected BIGINT NOT NULL DEFAULT 0,
    started_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at   TIMESTAMPTZ,
    PRIMARY KEY (run_id, step_name)
);

CREATE TABLE ctl.etl_watermark (
    source_table     TEXT PRIMARY KEY,
    last_received_at TIMESTAMPTZ,   -- append-only sources (stop events)
    last_updated_at  TIMESTAMPTZ    -- updatable sources (trips, students, ...)
);